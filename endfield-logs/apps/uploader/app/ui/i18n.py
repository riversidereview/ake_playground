def localize_boss_name(name: str | None, locale: str | None = None) -> str:
    loc = locale or _CURRENT_LOCALE
    if not name:
        return "-"
    trimmed = name.strip()
    if loc == "zh":
        return BOSS_NAME_ZH.get(trimmed, trimmed)
    return BOSS_NAME_EN.get(trimmed, trimmed)


def localize_character_name(name: str | None, locale: str | None = None) -> str:
    loc = locale or _CURRENT_LOCALE
    if not name:
        return "-"
    trimmed = name.strip()
    if loc == "zh":
        return CHARACTER_NAME_ZH.get(trimmed, trimmed)
    return CHARACTER_NAME_EN.get(trimmed, trimmed)


def localize_dungeon_name(name: str | None, locale: str | None = None) -> str:
    loc = locale or _CURRENT_LOCALE
    if not name:
        return "未知场地" if loc == "zh" else "Unknown Encounter"
    trimmed = name.strip()
    if loc == "zh":
        if trimmed in DUNGEON_NAME_ZH:
            return DUNGEON_NAME_ZH[trimmed]
        if ":" in trimmed:
            prefix, suffix = trimmed.split(":", 1)
            prefix_zh = DUNGEON_NAME_ZH.get(prefix.strip(), prefix.strip())
            suffix_zh = DUNGEON_NAME_ZH.get(suffix.strip(), suffix.strip())
            return f"{prefix_zh}·{suffix_zh}"
        if " · " in trimmed:
            prefix, suffix = trimmed.split(" · ", 1)
            prefix_zh = DUNGEON_NAME_ZH.get(prefix.strip(), prefix.strip())
            suffix_zh = DUNGEON_NAME_ZH.get(suffix.strip(), suffix.strip())
            return f"{prefix_zh} · {suffix_zh}"
        if "·" in trimmed:
            prefix, suffix = trimmed.split("·", 1)
            prefix_zh = DUNGEON_NAME_ZH.get(prefix.strip(), prefix.strip())
            suffix_zh = DUNGEON_NAME_ZH.get(suffix.strip(), suffix.strip())
            return f"{prefix_zh}·{suffix_zh}"
        return DUNGEON_NAME_ZH.get(trimmed, trimmed)

    # loc == "en"
    if trimmed in DUNGEON_NAME_EN:
        return DUNGEON_NAME_EN[trimmed]
    if "·" in trimmed:
        prefix, suffix = trimmed.split("·", 1)
        prefix_en = DUNGEON_NAME_EN.get(prefix.strip(), prefix.strip())
        suffix_en = DUNGEON_NAME_EN.get(suffix.strip(), suffix.strip())
        return f"{prefix_en}: {suffix_en}"
    if " · " in trimmed:
        prefix, suffix = trimmed.split(" · ", 1)
        prefix_en = DUNGEON_NAME_EN.get(prefix.strip(), prefix.strip())
        suffix_en = DUNGEON_NAME_EN.get(suffix.strip(), suffix.strip())
        return f"{prefix_en} · {suffix_en}"
    return DUNGEON_NAME_EN.get(trimmed, trimmed)
