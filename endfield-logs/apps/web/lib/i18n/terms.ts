export function getLocalizedDungeonName(dungeonName: string | null | undefined, locale: Locale): string {
  const trimmed = dungeonName?.trim() || "";
  if (!trimmed) {
    return locale === "en" ? "Unknown Encounter" : "未知首领";
  }
  if (locale === "en") {
    if (DUNGEON_NAME_EN[trimmed]) {
      return DUNGEON_NAME_EN[trimmed];
    }
    if (BOSS_NAME_EN[trimmed]) {
      return BOSS_NAME_EN[trimmed];
    }
    const shadowMatch = trimmed.match(/^影拓丰碑(\d+)期(?:[ ·・]*(.+))?/);
    if (shadowMatch) {
      const phase = shadowMatch[1];
      const sub = shadowMatch[2];
      return sub ? `Umbral Monument: Phase ${phase} · ${sub}` : `Umbral Monument: Phase ${phase}`;
    }
    return trimmed;
  }
  // locale === "zh"
  if (/[\u4e00-\u9fa5]/.test(trimmed)) {
    return trimmed;
  }
  if (DUNGEON_NAME_ZH[trimmed]) {
    return DUNGEON_NAME_ZH[trimmed];
  }
  if (BOSS_NAME_ZH[trimmed]) {
    return BOSS_NAME_ZH[trimmed];
  }
  const enShadowMatch = trimmed.match(/^(?:Umbral Monument|Monument of Shadows):\s*Phase\s*(\d+)(?:[ ·・]*(.+))?/i);
  if (enShadowMatch) {
    const phase = enShadowMatch[1];
    const sub = enShadowMatch[2];
    return sub ? `影拓丰碑${phase}期 · ${sub}` : `影拓丰碑${phase}期`;
  }
  const foundZh = Object.keys(DUNGEON_NAME_EN).find((zh) => DUNGEON_NAME_EN[zh] === trimmed);
  if (foundZh) {
    return foundZh;
  }
  return trimmed;
}

