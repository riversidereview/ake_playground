export function getLocalizedBuffName(
  buffName: string | null | undefined,
  eventKey: string | null | undefined,
  locale: Locale = "en"
): string {
  if (!buffName) return locale === "en" ? "Unknown Buff" : "未知效果";
  const trimmed = buffName.trim();
  if (!trimmed) return locale === "en" ? "Unknown Buff" : "未知效果";

  if (locale === "en") {
    if (BUFF_NAME_EN[trimmed]) {
      return BUFF_NAME_EN[trimmed];
    }
    // Handle composite strings separated by slashes, middle dots, commas
    if (trimmed.includes(" / ")) {
      return trimmed
        .split(" / ")
        .map((segment) => getLocalizedBuffName(segment, null, "en"))
        .join(" / ");
    }
    if (trimmed.includes(" · ")) {
      return trimmed
        .split(" · ")
        .map((segment) => getLocalizedBuffName(segment, null, "en"))
        .join(" · ");
    }
    if (trimmed.includes("、")) {
      return trimmed
        .split("、")
        .map((segment) => getLocalizedBuffName(segment, null, "en"))
        .join(", ");
    }
    if (trimmed.includes(" + ")) {
      return trimmed
        .split(" + ")
        .map((segment) => getLocalizedBuffName(segment, null, "en"))
        .join(" + ");
    }
    const charName = getLocalizedCharacterName(trimmed, "en");
    if (charName && charName !== trimmed) {
      return charName;
    }
    const bossName = getLocalizedBossName(trimmed, null, "en");
    if (bossName && bossName !== trimmed) {
      return bossName;
    }
    return trimmed;
  }

  // locale === "zh"
  if (BUFF_NAME_ZH[trimmed]) {
    return BUFF_NAME_ZH[trimmed];
  }
  if (trimmed.includes(" / ")) {
    return trimmed
      .split(" / ")
      .map((segment) => getLocalizedBuffName(segment, null, "zh"))
      .join(" / ");
  }
  if (trimmed.includes(" · ")) {
    return trimmed
      .split(" · ")
      .map((segment) => getLocalizedBuffName(segment, null, "zh"))
      .join(" · ");
  }
  if (trimmed.includes(" + ")) {
    return trimmed
      .split(" + ")
      .map((segment) => getLocalizedBuffName(segment, null, "zh"))
      .join(" + ");
  }
  const charName = getLocalizedCharacterName(trimmed, "zh");
  if (charName && charName !== trimmed) {
    return charName;
  }
  const bossName = getLocalizedBossName(trimmed, null, "zh");
  if (bossName && bossName !== trimmed) {
    return bossName;
  }
  return trimmed;
}

export function resolveAssetUrl(url?: string | null): string | null {
  if (!url) return null;
  const trimmed = url.trim();
  if (!trimmed) return null;
  if (trimmed.startsWith("http://") || trimmed.startsWith("https://")) {
    return trimmed;
  }
  const cdnBase = (typeof process !== "undefined" ? process.env.NEXT_PUBLIC_ASSET_CDN_URL : "")?.replace(/\/+$/, "");
  if (cdnBase) {
    const cleanPath = trimmed.startsWith("/") ? trimmed : `/${trimmed}`;
    return `${cdnBase}${cleanPath}`;
  }
  return trimmed.startsWith("/") ? trimmed : `/${trimmed}`;
}

export function getWeaponIconUrl(iconUrl?: string | null, weaponTemplate?: string | null): string | null {
  if (iconUrl) {
    return resolveAssetUrl(iconUrl);
  }
  const template = (weaponTemplate || "").trim();
  if (template) {
    return resolveAssetUrl(`/images/weapon/icon/${template}.png`);
  }
  return null;
}

