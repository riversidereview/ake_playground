export function getLocalizedWeaponName(
  nameOrId: string | null | undefined,
  locale: Locale = "en"
): string {
  if (!nameOrId) return "";
  const trimmed = nameOrId.trim();
  if (locale === "en") {
    if (WEAPON_NAME_EN[trimmed]) {
      return WEAPON_NAME_EN[trimmed];
    }
    const foundZh = Object.keys(WEAPON_NAME_ZH).find((k) => WEAPON_NAME_ZH[k] === trimmed);
    if (foundZh && WEAPON_NAME_EN[foundZh]) {
      return WEAPON_NAME_EN[foundZh];
    }
    return trimmed;
  }
  // locale === "zh"
  if (WEAPON_NAME_ZH[trimmed]) {
    return WEAPON_NAME_ZH[trimmed];
  }
  const foundEn = Object.keys(WEAPON_NAME_EN).find((k) => WEAPON_NAME_EN[k] === trimmed);
  if (foundEn && WEAPON_NAME_ZH[foundEn]) {
    return WEAPON_NAME_ZH[foundEn];
  }
  return trimmed;
}

